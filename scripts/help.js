function renderHelp(){
  var rail=document.getElementById("helpRail"), main=document.getElementById("helpMain");
  if(!rail||!main) return;
  var arts=hpArts();

  /* ── ریلِ سمت راست: دسته‌ها و مقاله‌های زیرشان ── */
  rail.innerHTML=HELP_CATS.map(function(c){
    var list=arts.filter(function(a){ return a.cat===c.id; });
    if(!list.length) return "";
    return '<div class="hp-group">'+
      '<div class="hp-gt"><svg viewBox="0 0 24 24">'+c.ic+'</svg>'+esc(c.fa)+'</div>'+
      list.map(function(a){
        return '<button class="hp-item'+(a.id===_hpArt?" sel":"")+'" onclick="hpOpen(\''+esc(a.id)+'\')">'+esc(a.t)+'</button>';
      }).join("")+
    '</div>';
  }).join("");

  /* ── ستونِ محتوا ── */
  if(_hpQ){ main.innerHTML=hpResultsHTML(); }
  else if(_hpArt){ main.innerHTML=hpArticleHTML(hpById(_hpArt)); }
  else { main.innerHTML=hpHomeHTML(); }
  main.scrollTop=0;

  /* اگر مقاله از بیرون باز شده باشد (دکمهٔ راهنمای یک بخش)، سلولِ متناظر در
     ریل ممکن است پایین‌ترِ ناحیهٔ دید باشد؛ فقط در همین حالت اسکرول می‌کنیم
     تا کاربر جای خودش را در فهرست ببیند. */
  var sel=rail.querySelector(".hp-item.sel");
  if(sel){
    var rr=rail.getBoundingClientRect(), sr=sel.getBoundingClientRect();
    if(sr.top<rr.top || sr.bottom>rr.bottom) rail.scrollTop += (sr.top-rr.top) - (rr.height-sr.height)/2;
  }
}

