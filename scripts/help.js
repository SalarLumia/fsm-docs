var _hpArt = null;    // شناسهٔ مقالهٔ باز (null = صفحهٔ نخستِ راهنما)
var _hpQ   = "";      // متنِ جست‌وجو

/* مقاله‌های قابلِ دیدن برای نقشِ کاربرِ جاری.
   ⚠ فیلترِ نقش تزئینی نیست: راهنمای کاری که کاربر اجازه‌اش را ندارد، فقط
   سردرگمی می‌سازد و او را دنبالِ دکمه‌ای می‌فرستد که در صفحه‌اش وجود ندارد. */
function hpArts(){
  var role=(typeof ME!=="undefined" && ME && ME.role) ? ME.role : "viewer";
  return HELP_ARTS.filter(function(a){ return !a.roles || a.roles.indexOf(role)>=0; });
}
function hpById(id){
  var all=hpArts();
  for(var i=0;i<all.length;i++) if(all[i].id===id) return all[i];
  return null;
}
function hpCat(id){
  for(var i=0;i<HELP_CATS.length;i++) if(HELP_CATS[i].id===id) return HELP_CATS[i];
  return null;
}
/* همهٔ متنِ یک مقاله در یک رشته — مبنای جست‌وجو.
   جست‌وجو باید متنِ کامل را ببیند نه فقط عنوان را، وگرنه کاربری که واژهٔ
   داخلِ یک گام را می‌جوید دست‌خالی برمی‌گردد. */
function hpFlat(a){
  var s=a.t+" "+(a.sub||"")+" "+(a.keys||"");
  (a.body||[]).forEach(function(b){
    if(b[0]==="steps"){ s+=" "+b[1].join(" "); }
    else if(b[0]==="table"){ s+=" "+b[1].join(" ")+" "+b[2].map(function(r){return r.join(" ");}).join(" "); }
    else if(b[0]!=="next"){ s+=" "+b[1]; }
  });
  return s;
}
/* نرمال‌سازیِ فارسی برای جست‌وجو. بدونِ این، «تایید» متنِ «تأیید» را پیدا
   نمی‌کرد و «جستجو» به «جست‌وجو» نمی‌رسید — و کاربر نتیجه‌گیری می‌کرد که
   راهنما چیزی در این باره ندارد.
   نیم‌فاصله حذف می‌شود نه اینکه به فاصله تبدیل شود: چون پرسشِ کاربر به واژه
   شکسته می‌شود و هر واژه جداگانه جست‌وجو می‌گردد، «پیش نمایش» و «پیشنمایش»
   هر دو داخلِ «پیشنمایش» پیدا می‌شوند. */
function hpNorm(s){
  return String(s||"")
    .replace(/[يی]/g,"ی").replace(/[كک]/g,"ک")
    .replace(/[أإآٱا]/g,"ا").replace(/[ؤئ]/g,"ی").replace(/ة/g,"ه")
    .replace(/[۰-۹]/g,function(d){ return String("۰۱۲۳۴۵۶۷۸۹".indexOf(d)); })
    .replace(/[‌ـ]/g,"").replace(/[ً-ْ]/g,"")
    .replace(/\s+/g," ").trim().toLowerCase();
}
function hpSearchHits(q){
  var n=hpNorm(q); if(!n) return [];
  var words=n.split(" ").filter(Boolean);
  return hpArts().map(function(a){
    var hay=hpNorm(hpFlat(a)), title=hpNorm(a.t), keys=hpNorm(a.keys||""), score=0;
    for(var i=0;i<words.length;i++){
      if(hay.indexOf(words[i])<0) return null;          // هر واژه باید جایی بیاید
      /* رتبه‌بندی: عنوان > واژه‌های کلیدی > متن. واژه‌های کلیدی جایی‌اند که
         مترادف‌ها می‌نشینند («جستجو» برای «جست‌وجو»)، پس باید از یک برخوردِ
         اتفاقی در متن جلوتر بیفتند. */
      if(title.indexOf(words[i])>=0) score+=10;
      else if(keys.indexOf(words[i])>=0) score+=5;
      score+=1;
    }
    return {a:a, score:score};
  }).filter(Boolean).sort(function(x,y){ return y.score-x.score; }).map(function(h){ return h.a; });
}

