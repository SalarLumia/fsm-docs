function hpCallout(kind,txt){
  var lbl={note:"نکته",warn:"هشدار",tip:"پیشنهاد"}[kind];
  return '<div class="hp-call hp-'+kind+'">'+
    '<svg viewBox="0 0 24 24">'+HP_IC[kind]+'</svg>'+
    '<div><span class="hp-call-l">'+lbl+'</span>'+esc(txt)+'</div></div>';
}
function hpBlock(b){
  var k=b[0];
  if(k==="p")    return '<p class="hp-p">'+esc(b[1])+'</p>';
  if(k==="kbd")  return '<div class="hp-kbd" dir="ltr">'+esc(b[1])+'</div>';
  if(k==="note"||k==="warn"||k==="tip") return hpCallout(k,b[1]);
  if(k==="steps"){
    /* شماره‌ها با faN فارسی می‌شوند و در نشانِ گردِ خودشان می‌نشینند؛ list-style
       پیش‌فرضِ مرورگر عددِ لاتین می‌دهد و با بقیهٔ سایت جور در نمی‌آید. */
    return '<ol class="hp-steps">'+b[1].map(function(s,i){
      return '<li><span class="hp-num">'+faN(i+1)+'</span><span class="hp-stxt">'+esc(s)+'</span></li>';
    }).join("")+'</ol>';
  }
  if(k==="table"){
    return '<div class="hp-tblwrap"><table class="hp-tbl"><thead><tr>'+
      b[1].map(function(h){ return '<th>'+esc(h)+'</th>'; }).join("")+
      '</tr></thead><tbody>'+
      b[2].map(function(r){ return '<tr>'+r.map(function(c){ return '<td>'+esc(c)+'</td>'; }).join("")+'</tr>'; }).join("")+
      '</tbody></table></div>';
  }
  if(k==="next"){
    /* هیچ مقاله‌ای نباید بن‌بست باشد: پایانِ هر مقاله مسیرِ بعدی را نشان می‌دهد. */
    var links=b[1].map(function(id){ return hpById(id); }).filter(Boolean);
    if(!links.length) return "";
    return '<div class="hp-next"><div class="hp-next-t">گامِ بعدی</div>'+
      links.map(function(a){
        return '<button class="hp-nextlink" onclick="hpOpen(\''+esc(a.id)+'\')">'+
          '<span>'+esc(a.t)+'</span>'+
          '<svg viewBox="0 0 24 24"><polyline points="15 18 9 12 15 6"/></svg></button>';
      }).join("")+'</div>';
  }
  return "";
}

