function hpOpen(id){
  _hpArt=id; _hpQ="";
  var box=document.getElementById("helpSearch"); if(box) box.value="";
  hpClearBtn();
  renderHelp();
}
function hpHome(){ _hpArt=null; _hpQ=""; var b=document.getElementById("helpSearch"); if(b) b.value=""; hpClearBtn(); renderHelp(); }
function hpOnSearch(v){ _hpQ=String(v||"").trim(); if(_hpQ) _hpArt=null; hpClearBtn(); renderHelp(); }
function hpClearSearch(){ var b=document.getElementById("helpSearch"); if(b){ b.value=""; b.focus(); } _hpQ=""; hpClearBtn(); renderHelp(); }
function hpClearBtn(){
  var x=document.getElementById("helpClear"); if(x) x.style.display=_hpQ?"":"none";
}
